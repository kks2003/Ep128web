#!/usr/bin/env python3
"""Generates web/src/card/tvc-card-data.c: the power-on contents of the
TVC256k++ card's fast RAM (font and background image), from the card
repository's sources/firmware/TVC-IO/binaries (MIT license, Vass Sandor).

usage: gen_card_data.py <tvc256kplusplus repo> <output .c>
"""
import sys, os

repo, out = sys.argv[1], sys.argv[2]
binaries = os.path.join(repo, 'sources', 'firmware', 'TVC-IO', 'binaries')
font = open(os.path.join(binaries, 'c16-hungarian.bin'), 'rb').read()
bmp = open(os.path.join(binaries, 'tvc-16cimage.bmp'), 'rb').read()
assert len(font) == 2048
# preinit_core_gfx(): 240 lines of 128 bytes from offset 118, bottom-up
bitmap = bytearray(240 * 128)
for i in range(240):
    for j in range(128):
        bitmap[i * 128 + j] = bmp[(239 - i) * 128 + j + 118]

def arr(name, data):
    lines = ['const uint8_t %s[%d] = {' % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append('  ' + ','.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)

with open(out, 'w') as f:
    f.write('/* Generated by scripts/gen_card_data.py from the TVC256k++ firmware\n'
            ' * binaries (c16-hungarian.bin, tvc-16cimage.bmp), MIT license,\n'
            ' * see dikdom/tvc256kplusplus. */\n')
    f.write('#include "tvc-card.h"\n\n')
    f.write(arr('card_font_data', font) + '\n\n')
    f.write(arr('card_bitmap_data', bitmap) + '\n')
