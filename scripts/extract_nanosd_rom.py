#!/usr/bin/env python3
"""Writes web/src/tvc_nanosd_rom.cpp from the TVC-NanoSD EEPROM image
(dikdom/TVC-NanoSD bin/NanoSDROM-v*.bin, BSD-3-Clause): the 8 kB of the card
ROM at $C000-$DFFF of the 64 kB image.
    python3 scripts/extract_nanosd_rom.py NanoSDROM-v0.33.bin"""
import os, sys

src = sys.argv[1]
data = open(src, "rb").read()
rom = data[0xC000:0xE000]
assert rom[:4] == b"MOPS", "not a NanoSD EEPROM image"
out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "web/src/tvc_nanosd_rom.cpp")
with open(out, "w") as f:
    f.write("// Generated by scripts/extract_nanosd_rom.py from %s\n" % os.path.basename(src))
    f.write("// TVC-NanoSD IO card ROM ($C000-$DFFF), BSD-3-Clause, (c) 2021 dikdom,\n")
    f.write("// see https://github.com/dikdom/TVC-NanoSD and web/src/LICENSE-TVC-NanoSD.txt\n")
    f.write("#include <cstdint>\n#include <cstddef>\n\n")
    f.write("extern const uint8_t tvc_nanosd_rom_data[%d] = {\n" % len(rom))
    for i in range(0, len(rom), 16):
        f.write("  " + ",".join("0x%02X" % b for b in rom[i:i + 16]) + ",\n")
    f.write("};\nextern const size_t tvc_nanosd_rom_size = %d;\n" % len(rom))
print("wrote", out, len(rom), "bytes")
