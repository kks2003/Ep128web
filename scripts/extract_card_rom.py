#!/usr/bin/env python3
"""Extracts the 12 kB IO ROM of the TVC256k++ card from a firmware .uf2 file
and writes web/src/tvc256kpp_rom.cpp (the ROM is the assembled output of
sources/firmware/TVC-IO/Z80/tvc-256k++.asm in the dikdom/tvc256kplusplus repo).

usage: extract_card_rom.py TVC-IO-v0.24.uf2 [out.cpp]
"""
import struct, sys

def main():
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else "web/src/tvc256kpp_rom.cpp"
    d = open(src, "rb").read()
    blocks = {}
    for i in range(0, len(d), 512):
        b = d[i:i + 512]
        _, _, _, addr, size, _, _, _ = struct.unpack("<8I", b[:32])
        blocks[addr] = b[32:32 + size]
    lo, hi = min(blocks), max(blocks) + 256
    img = bytearray(b"\xff" * (hi - lo))
    for a, v in blocks.items():
        img[a - lo:a - lo + len(v)] = v
    s = bytes(img).find(b"MOPS\x06256k++")
    if s < 0:
        sys.exit("card ROM header not found")
    rom = bytes(img[s:s + 0x3000])
    with open(dst, "w") as f:
        f.write("// Generated by scripts/extract_card_rom.py from %s\n" % src.split("/")[-1])
        f.write("// TVC256k++ IO ROM (2 x 6 kB pages), GPL-3.0, see dikdom/tvc256kplusplus\n")
        f.write("#include <cstdint>\n#include <cstddef>\n\n")
        f.write("extern const uint8_t tvc256kpp_rom_data[%d] = {\n" % len(rom))
        for i in range(0, len(rom), 16):
            f.write("  " + ",".join("0x%02X" % x for x in rom[i:i + 16]) + ",\n")
        f.write("};\nextern const size_t tvc256kpp_rom_size = %d;\n" % len(rom))
    print("wrote", dst, len(rom), "bytes")

main()
