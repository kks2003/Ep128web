#!/usr/bin/env python3
# Generates web/shell/ep-configs.js: the Enterprise machine configurations of
# ep128emu's installer (ep128emu/installer/makecfg.cpp, the configurations
# its "makecfg" writes: ep128uk/, ep128hun/, ep128esp/, ep128brd/, ep64/),
# each with its RAM size and ROMs (file, segments), for the page's
# "Enterprise setup" window.
#
# Usage: python3 scripts/gen_ep_configs.py  (from the repository root)

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'ep128emu', 'installer', 'makecfg.cpp')
OUT = os.path.join(ROOT, 'web', 'shell', 'ep-configs.js')


def main():
    src = open(SRC, encoding='utf-8').read()

    # RAM sizes: EP_RAM_xxxK uint64_t(n)
    ram = {}
    for name, kb, n in re.findall(r'#define\s+(EP_RAM_(\d+)K)\s+uint64_t\((\d+)\)', src):
        ram[name] = int(kb)

    # ROM files: "#define EP_ROM_X (uint64_t(1) << n)" then { "file", 0x...U }
    roms = {}
    for name, file, segs in re.findall(
            r'#define\s+(EP_ROM_\w+)\s+\(uint64_t\(1\)\s*<<\s*\d+\)\s*\n\s*\{\s*"([^"]+)",\s*(0x[0-9A-Fa-f]+)U\s*\}',
            src):
        roms[name] = (file, int(segs, 16))
    if len(roms) < 50:
        sys.exit('could not read the ROM table of makecfg.cpp')

    table = src[src.index('machineConfigs[] = {'):]
    table = table[:table.index('};')]
    configs = []
    for path, expr in re.findall(r'\{\s*"((?:ep128\w+|ep64)/[^"]+)\.cfg",\s*([^}]*)\}', table):
        names = re.findall(r'EP_\w+', expr)
        cfg = {'path': path, 'ram': None, 'roms': [], 'sdext': None}
        for n in names:
            if n in ram:
                cfg['ram'] = ram[n]
                continue
            if n not in roms:
                sys.exit('unknown flag %s in %s' % (n, path))
            file, code = roms[n]
            segs = []
            # one byte per 16 KB page of the file, highest first; FFh: no more
            # pages; bit 7: the SDEXT flash ROM (segment 07h)
            for j in range(4):
                b = (code >> (24 - 8 * j)) & 0xFF
                if b == 0xFF:
                    break
                segs.append(b & 0x7F)
                if b & 0x80:
                    cfg['sdext'] = file
            cfg['roms'].append([file, segs])
        if cfg['ram'] is None:
            cfg['ram'] = 64                    # EP_RAM_64K is 0: no flag
        configs.append(cfg)
    if len(configs) < 60:
        sys.exit('could not read the machine configurations of makecfg.cpp')

    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/gen_ep_configs.py from ep128emu/installer/makecfg.cpp:\n')
        f.write('// the Enterprise configurations of ep128emu (path: its .cfg file without\n')
        f.write('// the extension, ram: KB, roms: [file, [segment of each 16 KB page]],\n')
        f.write('// sdext: the SDEXT flash ROM). Do not edit.\n')
        f.write('window.EP_CONFIGS = [\n')
        f.write(',\n'.join('  ' + json.dumps(c, separators=(',', ':')) for c in configs))
        f.write('\n];\n')
    print('%d configurations -> %s' % (len(configs), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
